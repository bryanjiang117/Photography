/**
 * Generate per-photo width/height from full-size AVIFs for skeleton placeholders.
 *
 *   npm run photos:ratios
 *   node scripts/generate-gallery-aspect-ratios.mjs --region=china
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PHOTOS_ROOT = path.join(__dirname, "../public/assets/photos");
const OUT = path.join(__dirname, "../src/constants/galleryAspectRatios.js");
const REGIONS = ["mexico", "canada", "china", "japan"];

function listFullAvifs(regionDir) {
  return fs
    .readdirSync(regionDir)
    .filter(
      (f) =>
        f.endsWith(".avif") &&
        !f.endsWith("-sm.avif") &&
        !f.endsWith("-md.avif"),
    )
    .map((f) => f.replace(/\.avif$/, ""));
}

async function ratiosForRegion(region) {
  const dir = path.join(PHOTOS_ROOT, region);
  if (!fs.existsSync(dir)) return {};

  /** @type {Record<string, { w: number; h: number }>} */
  const out = {};
  for (const name of listFullAvifs(dir)) {
    const meta = await sharp(path.join(dir, `${name}.avif`)).metadata();
    if (!meta.width || !meta.height) continue;
    out[name] = { w: meta.width, h: meta.height };
  }
  return out;
}

const regionArg = process.argv
  .find((a) => a.startsWith("--region="))
  ?.split("=")[1];
const regions = regionArg ? [regionArg] : REGIONS;

/** @type {Record<string, Record<string, { w: number; h: number }>>} */
const data = {};
for (const region of regions) {
  console.log(region);
  data[region] = await ratiosForRegion(region);
  console.log(`  ${Object.keys(data[region]).length} photos`);
}

const content = `/** Auto-generated by scripts/generate-gallery-aspect-ratios.mjs — do not edit */
export const GALLERY_ASPECT_RATIOS = ${JSON.stringify(data, null, 2)};

/** @returns {{ w: number; h: number } | null} */
export function galleryPhotoDimensions(region, name) {
  return GALLERY_ASPECT_RATIOS[region]?.[name] ?? null;
}
`;

fs.writeFileSync(OUT, content);
console.log(`\nWrote ${OUT}`);
